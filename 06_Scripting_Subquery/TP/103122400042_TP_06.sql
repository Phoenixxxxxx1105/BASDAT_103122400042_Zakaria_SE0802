SELECT 
    F.JUDUL || ' adalah film dengan durasi terpendek yaitu ' || F.DURASI || 
    ' Menit, yang ditonton dengan umur termuda, yaitu ' || 
    MIN(EXTRACT(YEAR FROM TO_DATE('2020-01-01', 'YYYY-MM-DD')) - EXTRACT(YEAR FROM M.TGL_LAHIR)) || 
    ' Tahun' AS KETERANGAN
FROM FILM_103122400042 F
JOIN JADWAL_103122400042 J ON F.ID_FILM = J.ID_FILM
JOIN TRANSAKSI_103122400042 T ON J.ID_JADWAL = T.ID_JADWAL
JOIN MEMBER_103122400042 M ON T.ID_MEMBER = M.ID_MEMBER
WHERE F.DURASI = (SELECT MIN(DURASI) FROM FILM_103122400042)
GROUP BY F.JUDUL, F.DURASI;

SELECT 
    TH.ID_THEATER AS NOMOR_TEATER, 
    TH.KELAS, 
    COUNT(J.ID_JADWAL) AS "TOTAL PEMAKAIAN"
FROM THEATER_103122400042 TH
JOIN JADWAL_103122400042 J ON TH.ID_THEATER = J.ID_THEATER
GROUP BY TH.ID_THEATER, TH.KELAS
HAVING COUNT(J.ID_JADWAL) = (
    SELECT MAX(COUNT(ID_JADWAL))
    FROM JADWAL_103122400042
    GROUP BY ID_THEATER
);

