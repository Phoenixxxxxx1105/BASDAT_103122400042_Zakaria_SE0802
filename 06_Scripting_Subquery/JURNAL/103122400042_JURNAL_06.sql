SELECT DISTINCT 
    M.NAMA AS NAMA_MEMBER, 
    (2021 - EXTRACT(YEAR FROM M.TGL_LAHIR)) AS UMUR
FROM MEMBER_103122400042 M
JOIN TRANSAKSI_103122400042 T ON M.ID_MEMBER = T.ID_MEMBER
JOIN JADWAL_103122400042 J ON T.ID_JADWAL = J.ID_JADWAL
JOIN FILM_103122400042 F ON J.ID_FILM = F.ID_FILM
JOIN THEATER_103122400042 TH ON J.ID_THEATER = TH.ID_THEATER
WHERE F.JUDUL = 'Habibie Ainun 3'
  AND TH.HARGA > (
      SELECT HARGA 
      FROM THEATER_103122400042 
      WHERE ID_THEATER = 'Teater 1'
  );
  
  SELECT F.JUDUL, TH.HARGA
FROM FILM_103122400042 F
JOIN JADWAL_103122400042 J ON F.ID_FILM = J.ID_FILM
JOIN THEATER_103122400042 TH ON J.ID_THEATER = TH.ID_THEATER
WHERE TH.HARGA = (SELECT MIN(HARGA) FROM THEATER_103122400042)
   OR TH.HARGA = (SELECT MAX(HARGA) FROM THEATER_103122400042)
ORDER BY TH.HARGA ASC;

SELECT F.JUDUL, COUNT(J.ID_JADWAL) AS "JUMLAH TAYANG"
FROM FILM_103122400042 F
JOIN JADWAL_103122400042 J ON F.ID_FILM = J.ID_FILM
GROUP BY F.JUDUL
HAVING COUNT(J.ID_JADWAL) > (
    SELECT MIN(JUMLAH_TAYANG)
    FROM (
        SELECT COUNT(ID_JADWAL) AS JUMLAH_TAYANG
        FROM JADWAL_103122400042
        GROUP BY ID_FILM
    )
);

SELECT TH.ID_THEATER AS ID_TEATER, F.JUDUL, COUNT(J.ID_JADWAL) AS "JUMLAH TAYANG"
FROM THEATER_103122400042 TH
JOIN JADWAL_103122400042 J ON TH.ID_THEATER = J.ID_THEATER
JOIN FILM_103122400042 F ON J.ID_FILM = F.ID_FILM
WHERE F.DURASI > 100
GROUP BY TH.ID_THEATER, F.JUDUL
HAVING COUNT(J.ID_JADWAL) > (
    SELECT AVG(JUMLAH_TAYANG)
    FROM (
        SELECT COUNT(ID_JADWAL) AS JUMLAH_TAYANG
        FROM JADWAL_103122400042
        GROUP BY ID_THEATER, ID_FILM
    )
);

SELECT DISTINCT M.NAMA AS NAMA_MEMBER, M.NO_HP, F.JUDUL
FROM MEMBER_103122400042 M
JOIN TRANSAKSI_103122400042 T ON M.ID_MEMBER = T.ID_MEMBER
JOIN JADWAL_103122400042 J ON T.ID_JADWAL = J.ID_JADWAL
JOIN FILM_103122400042 F ON J.ID_FILM = F.ID_FILM
WHERE M.NO_HP LIKE '081%'
  AND J.ID_THEATER IN (
      SELECT ID_THEATER 
      FROM THEATER_103122400042 
      WHERE HARGA > 30000
  );