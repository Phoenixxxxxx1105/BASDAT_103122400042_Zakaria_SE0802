SELECT 
    j.ID_JADWAL, 
    f.JUDUL, 
    j.ID_THEATER, 
    j.PERIODE_START, 
    EXTRACT(DAY FROM (CAST(j.PERIODE_END AS TIMESTAMP) - CAST(j.PERIODE_START AS TIMESTAMP))) || ' hari' AS LAMA_WAKTU
FROM JADWAL_103122400042 j
JOIN FILM_103122400042 f ON j.ID_FILM = f.ID_FILM
WHERE f.JUDUL = 'Habibie Ainun 3';

SELECT 
    j.ID_THEATER, 
    f.JUDUL, 
    t.KELAS, 
    t.HARGA,
    CASE 
        WHEN t.HARGA < 50000 THEN 'Murah'
        WHEN t.HARGA > 75000 THEN 'Mahal'
        ELSE 'Normal'
    END AS KATEGORI
FROM JADWAL_103122400042 j
JOIN FILM_103122400042 f ON j.ID_FILM = f.ID_FILM
JOIN THEATER_103122400042 t ON j.ID_THEATER = t.ID_THEATER;

SELECT 
    m.ID_MEMBER, 
    t.HARGA AS HARGA_AWAL, 
    TRUNC(MONTHS_BETWEEN(SYSDATE, m.TGL_LAHIR) / 12) AS UMUR,
    CASE 
        WHEN TRUNC(MONTHS_BETWEEN(SYSDATE, m.TGL_LAHIR) / 12) <= 32 THEN t.HARGA - (t.HARGA * 0.10)
        ELSE t.HARGA 
    END AS SALE
FROM TRANSAKSI_13122400042 tr
JOIN MEMBER_103122400042 m ON tr.ID_MEMBER = m.ID_MEMBER
JOIN JADWAL_103122400042 j ON tr.ID_JADWAL = j.ID_JADWAL
JOIN THEATER_103122400042 t ON j.ID_THEATER = t.ID_THEATER
ORDER BY UMUR ASC;

SELECT 
    m.ID_MEMBER, 
    m.NAMA AS "NAMA MEMBER", 
    f.JUDUL
FROM MEMBER_103122400042 m
JOIN TRANSAKSI_13122400042 tr ON m.ID_MEMBER = tr.ID_MEMBER
JOIN JADWAL_103122400042 j ON tr.ID_JADWAL = j.ID_JADWAL
JOIN FILM_103122400042 f ON j.ID_FILM = f.ID_FILM
WHERE f.DURASI >= 100 
  AND TO_NUMBER(SUBSTR(m.NO_HP, -1, 1)) = 8;
  
SELECT 
    tr.ID_MEMBER, 
    j.ID_FILM, 
    j.ID_THEATER AS ID_TEATER, 
    t.HARGA,
    CASE 
        WHEN f.JUDUL = 'Keluarga Cemara' AND tr.TANGGAL >= TO_DATE('2019-06-19', 'YYYY-MM-DD') THEN t.HARGA * 0.70
        ELSE t.HARGA 
    END AS "Sale"
FROM TRANSAKSI_13122400042 tr
JOIN JADWAL_103122400042 j ON tr.ID_JADWAL = j.ID_JADWAL
JOIN THEATER_103122400042 t ON j.ID_THEATER = t.ID_THEATER
JOIN FILM_103122400042 f ON j.ID_FILM = f.ID_FILM;
