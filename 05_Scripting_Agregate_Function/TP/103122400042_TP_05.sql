SELECT COUNT(ID_FILM) AS JUMLAH_FILM 
FROM FILM_103122400042;

SELECT COUNT(DISTINCT ID_FILM) AS FILM_DIPUTAR 
FROM JADWAL_103122400042;

SELECT ID_MEMBER, COUNT(KODE_PEMESANAN) AS JUMLAH_NONTON
FROM TRANSAKSI_13122400042
GROUP BY ID_MEMBER
HAVING COUNT(KODE_PEMESANAN) > 2;

SELECT 
    m.ID_MEMBER, 
    m.NAMA, 
    m.TGL_LAHIR, 
    COUNT(t.KODE_PEMESANAN) AS JUMLAH_NONTON
FROM MEMBER_103122400042 m
LEFT JOIN TRANSAKSI_13122400042 t ON m.ID_MEMBER = t.ID_MEMBER
WHERE m.TGL_LAHIR = (SELECT MAX(TGL_LAHIR) FROM MEMBER_103122400042)
GROUP BY m.ID_MEMBER, m.NAMA, m.TGL_LAHIR;

SELECT 
    EXTRACT(MONTH FROM TGL_LAHIR) AS BULAN_LAHIR, 
    COUNT(ID_MEMBER) AS JUMLAH_MEMBER
FROM MEMBER_103122400042
GROUP BY EXTRACT(MONTH FROM TGL_LAHIR)
ORDER BY BULAN_LAHIR ASC;

SELECT 
    f.JUDUL, 
    COUNT(j.ID_JADWAL) AS JUMLAH_JADWAL
FROM JADWAL_103122400042 j
JOIN FILM_103122400042 f ON j.ID_FILM = f.ID_FILM
GROUP BY f.JUDUL;