SELECT 
    j.ID_THEATER, 
    f.JUDUL,
    SUM(t.HARGA) AS TOTAL_PENDAPATAN
FROM TRANSAKSI_13122400042 tr
JOIN JADWAL_103122400042 j ON tr.ID_JADWAL = j.ID_JADWAL
JOIN FILM_103122400042 f ON j.ID_FILM = f.ID_FILM
JOIN THEATER_103122400042 t ON j.ID_THEATER = t.ID_THEATER
GROUP BY j.ID_THEATER, f.JUDUL
HAVING SUM(t.HARGA) > 150000;

SELECT * FROM (
    SELECT 
        f.JUDUL, 
        COUNT(tr.KODE_PEMESANAN) AS "MAX(JUMLAH)"
    FROM TRANSAKSI_13122400042 tr
    JOIN JADWAL_103122400042 j ON tr.ID_JADWAL = j.ID_JADWAL
    JOIN FILM_103122400042 f ON j.ID_FILM = f.ID_FILM
    WHERE tr.STATUS = 'pesan'
    GROUP BY f.JUDUL
    ORDER BY COUNT(tr.KODE_PEMESANAN) DESC
)
WHERE ROWNUM = 1;

SELECT 
    j.ID_THEATER, 
    AVG(t.HARGA) AS "AVG(HARGA)"
FROM TRANSAKSI_13122400042 tr
JOIN JADWAL_103122400042 j ON tr.ID_JADWAL = j.ID_JADWAL
JOIN THEATER_103122400042 t ON j.ID_THEATER = t.ID_THEATER
GROUP BY j.ID_THEATER
ORDER BY j.ID_THEATER ASC;

SELECT 
    f.JUDUL, 
    j.ID_THEATER, 
    COUNT(j.ID_FILM) AS "COUNT(ID_FILM)"
FROM JADWAL_103122400042 j
JOIN FILM_103122400042 f ON j.ID_FILM = f.ID_FILM
WHERE f.JUDUL = 'Habibie Ainun 3'
GROUP BY f.JUDUL, j.ID_THEATER
ORDER BY j.ID_THEATER ASC;